/**
 * Environment configuration of the `materialIndexTrigger` Lambda (Task 4.6).
 *
 * The variables are set by
 * `amplify/backend/function/materialIndexTrigger/materialIndexTrigger-cloudformation-template.json`:
 * the Knowledge Base / data source ids come from the function's environment
 * variable parameters, the table name from the AppSync API's exports.
 */
import { DEFAULT_INDEXER_CONFIG, type IndexerConfig } from './indexMaterial';

export const ENV_KNOWLEDGE_BASE_ID = 'KNOWLEDGE_BASE_ID';
export const ENV_DATA_SOURCE_ID = 'DATA_SOURCE_ID';
/** Amplify's standard variable for an `@model` table a function can access. */
export const ENV_MATERIAL_FILE_TABLE = 'API_FMIOS_MATERIALFILETABLE_NAME';

/** GSI generated by `studentId: ID! @index(name: "byStudent")` on `MaterialFile`. */
export const MATERIAL_FILE_STUDENT_INDEX = 'byStudent';

const BEDROCK_ID_PATTERN = /^[0-9a-zA-Z]{10}$/;

export interface TriggerConfig {
  knowledgeBaseId: string;
  dataSourceId: string;
  materialFileTableName: string;
  materialFileStudentIndex: string;
  indexer: IndexerConfig;
}

/** Thrown when the Lambda is mis-configured; lists every problem at once. */
export class ConfigError extends Error {
  readonly problems: readonly string[];

  constructor(problems: readonly string[]) {
    super(`materialIndexTrigger is mis-configured: ${problems.join('; ')}`);
    this.name = 'ConfigError';
    this.problems = problems;
  }
}

export function loadConfig(env: Readonly<Record<string, string | undefined>>): TriggerConfig {
  const problems: string[] = [];
  const knowledgeBaseId = readBedrockId(env, ENV_KNOWLEDGE_BASE_ID, problems);
  const dataSourceId = readBedrockId(env, ENV_DATA_SOURCE_ID, problems);
  const materialFileTableName = (env[ENV_MATERIAL_FILE_TABLE] ?? '').trim();
  if (materialFileTableName === '') {
    problems.push(`${ENV_MATERIAL_FILE_TABLE} is not set`);
  }
  if (problems.length > 0) {
    throw new ConfigError(problems);
  }
  return {
    knowledgeBaseId,
    dataSourceId,
    materialFileTableName,
    materialFileStudentIndex: MATERIAL_FILE_STUDENT_INDEX,
    indexer: DEFAULT_INDEXER_CONFIG,
  };
}

function readBedrockId(
  env: Readonly<Record<string, string | undefined>>,
  name: string,
  problems: string[]
): string {
  const value = (env[name] ?? '').trim();
  if (value === '') {
    problems.push(`${name} is not set`);
  } else if (!BEDROCK_ID_PATTERN.test(value)) {
    problems.push(`${name} must be a 10-character alphanumeric Bedrock id`);
  }
  return value;
}
